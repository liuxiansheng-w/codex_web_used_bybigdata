import { access, readFile, writeFile } from 'node:fs/promises';

// Publish a local module so either service can be deployed independently.
// Only public/sql-parser.js is maintained by hand.
const source = new URL('../public/sql-parser.js', import.meta.url);
const target = new URL('../../dgc-sql-runner/public/sql-parser.mjs', import.meta.url);
const expected = '// Generated by codex-web-shell/scripts/build-sql-parser.mjs. Do not edit.\n' + await readFile(source, 'utf8');
if (process.argv.includes('--check')) {
  try { await access(new URL('../../dgc-sql-runner/server.mjs', import.meta.url)); }
  catch (error) { if (error.code !== 'ENOENT') throw error; console.log('SQL runner not installed; standalone workbench parser checked.'); process.exit(0); }
  const actual = await readFile(target, 'utf8').catch(() => null);
  if (actual !== expected) throw new Error('SQL parser is out of sync. Run npm run build:sql-parser before loading either service.');
  console.log('Workbench and SQL runner use the same parameter parser.');
} else {
  await writeFile(target, expected);
  console.log('Built the SQL runner parameter module.');
}
